/**
 * Product data contract (REVISION.md §19) — no image, no name, no personal
 * data: only structured diagnosis, stored locally (IndexedDB).
 */
import type { CodeErreur } from './taxonomy'

export type Erreur = {
  code: CodeErreur
  libelle: string
  /** Textual excerpt of the faulty line — never the image. */
  ligne: string
  /** ≤ 25 words, caring tone (never "you made 4 mistakes"). */
  explication: string
  /** 0..1 */
  confiance: number
  /** false for E11 (copying): reported but with zero weight in the profile. */
  ponderee: boolean
  /** Area of the error in the image, in relative coordinates (0..1). */
  zone?: Zone
}

export type Zone = { x: number; y: number; largeur: number; hauteur: number }

export type Diagnostic = {
  id: string
  createdAt: string
  matiere: 'maths'
  nbFautes: number
  erreurs: Erreur[]
  /** null if no weighted error (clean paper or only E11/E99). */
  typeDominant: CodeErreur | null
}

export type Profil = {
  /** Weighted occurrences by type (E99 excluded, E11 weight 0). */
  parType: Record<CodeErreur, number>
  totalAnalyses: number
  evolution: { date: string; typeDominant: CodeErreur | null }[]
  /** Extension: reported but unweighted occurrences (E11, E99). */
  signalees: Partial<Record<CodeErreur, number>>
}

export type Exercice = {
  enonce: string
  indices: string[]
  solution: string
  /** Error type worked on — verified by the safety check (§18.3). */
  typeTravaille: CodeErreur
  niveau: string
  /** 0 = drawn from the local bank (no network call); ≥ 1 = generated by the model. */
  tentative: number
  /** Exercise identifier (bank) or "modele-N" for a fresh exercise. */
  id?: string
  /** Provenance: local or model. */
  source?: 'banque' | 'modele'
}

export type VerdictGardeFou = {
  travailleLeBonType: boolean
  neDonneLaSolutionOrigine: boolean
  memeNiveau: boolean
  motifs: string[]
}

export type ExerciceVerifie = {
  exercice: Exercice
  verdict: VerdictGardeFou
}

/** Pipeline steps (§18.2) — waiting becomes a demonstration. */
export type EtapeId = 'ingest' | 'anonymise' | 'extrait' | 'classifie' | 'agrege' | 'genere'

export type EtatEtape = 'attente' | 'en-cours' | 'fait' | 'echec' | 'sautee'

export type Progression = {
  etape: EtapeId
  etat: EtatEtape
  message?: string
  ms?: number
  /**
   * Proof that the step **actually** produced something: "3 annotations
   * detected", "E01, E01, E11", "safety check 3/3". This is what makes the
   * pipeline readable and verifiable, not a progress bar that moves.
   */
  preuve?: string
}

export type Annotation = {
  /** Line (or formula) as read on the paper. */
  ligne: string
  /** Teacher's annotation (highlighting, "wrong", "sign!", grade…). */
  annotation: string
  /** What the student wrote, if legible. */
  eleve?: string
  /** What should have been written, if identifiable. */
  attendu?: string
  zone?: Zone
}

export type Extraction = {
  annotations: Annotation[]
  /** Paper with no annotations: "clean paper" case (RNF-04). */
  copiePropre: boolean
  /** Detected name (masked client-side, never persisted or sent to the profile). */
  nomDetecte?: string
}

/** Second-pass summary (batch 3): displayed for transparency. */
export type BilanRevue = { revues: number; modifiees: number }

export type ResultatAnalyse = {
  diagnostic: Diagnostic
  extraction: Extraction
  /** Number of errors re-checked and modified by the second pass. */
  revue?: BilanRevue
  /** Anonymized image, in session memory only: never persisted. */
  imageAnonymisee: string
  exercice: ExerciceVerifie | null
  /** Honest message when no relevant exercise could be produced. */
  messageExercice?: string
}

export type Reglages = {
  /** Personal key (BYOK): safety net if the proxy quota is exhausted. */
  clePersonnelle: string
  modele: string
  /** Edge proxy URL; empty = same-origin /api/analyze proxy. */
  proxy: string
}

export type EtapeDiagnostic = { profil: Profil; diagnostic: Diagnostic }

/** Class statistic (teacher mode, RF-20). */
export type StatsClasse = {
  nbCopies: number
  parType: Record<CodeErreur, number>
  typeLePlusFrequent: CodeErreur | null
  pourcentageTypeFrequent: number
  copiesParType: { id: string; typeDominant: CodeErreur | null }[]
}
